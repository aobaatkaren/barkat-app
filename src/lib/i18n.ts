/** Keeps "20:00–22:00" in the right order inside Urdu (RTL) text. */
export function timeRange(a: string, b: string) {
  return `\u2066${a}–${b}\u2069`;
}

export function formatPKR(n: number) {
  return 'Rs ' + n.toLocaleString('en-PK');
}
